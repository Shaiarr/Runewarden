    /** Forestry timed species only. Planted trees are excluded by the caller. */
    static int treeLifetimeTicks(String rawName)
    {
        String name = rawName == null ? "" : rawName.toLowerCase(Locale.ROOT);
        switch (name)
        {
            case "oak": case "oak tree": return 45;
            case "willow": case "willow tree": return 50;
            case "teak": case "teak tree": return 50;
            case "maple tree": case "mahogany": case "mahogany tree": return 100;
            case "hollow tree": return 60;
            case "arctic pine": case "arctic pine tree": return 140;
            case "yew": case "yew tree": return 190;
            case "magic tree": return 390;
            case "redwood": case "redwood tree": return 440;
            default: return 0;
        }
    }

    static long remainingMillis(long startedAt, int ticks, long now)
    {
        return Math.max(0L, ticks * 600L - Math.max(0L, now - startedAt));
    }

    static String countdown(long millis)
    {
        long seconds = (millis + 999L) / 1000L;
        return seconds >= 60 ? (seconds / 60) + ":" + String.format(Locale.ROOT, "%02d", seconds % 60)
            : seconds + "s";
    }
